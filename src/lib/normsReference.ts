const BY_ATHLETE = new Map<string, DrillReferenceStat[]>(
  RAW_DATA.map(([athlete, ...nums]) => {
    const stats: DrillReferenceStat[] = []
    for (let i = 0; i < NORMALIZED_DRILL_NAMES.length; i++) {
      stats.push({ percentile: nums[i * 2], rank: nums[i * 2 + 1] })
    }
    return [normalizeName(athlete as unknown as string), stats]
  })
)

export function getReferenceStat(
  playerName: string | null | undefined,
  subcategoryName: string | null | undefined
): DrillReferenceStat | null {
  if (!playerName || !subcategoryName) return null
  const athleteStats = BY_ATHLETE.get(normalizeName(playerName))
  if (!athleteStats) return null
  const drillIndex = NORMALIZED_DRILL_NAMES.indexOf(normalizeName(subcategoryName))
  if (drillIndex === -1) return null
  return athleteStats[drillIndex] ?? null
}
